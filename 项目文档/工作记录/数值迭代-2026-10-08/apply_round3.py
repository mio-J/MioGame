HERE = Path(__file__).resolve().parent
DOC = HERE.parents[1] / '设计文档'
changed = []

def edit(rel, old_version, new_version, fn, note):
    p = DOC / rel
    s = p.read_text(encoding='utf-8-sig')
    s = fn(s)
    if '| 版本' in s:
        s, n = re.subn(r'(?m)^(\|\s*版本\s*\|\s*)' + re.escape(old_version) + r'(\s*\|)', rf'\g<1>{new_version}\2', s, count=1)
        assert n == 1, (rel, 'version')
    else:
        assert f'版本 {old_version}' in s
        s = s.replace(f'版本 {old_version}', f'版本 {new_version}', 1)
    s += f'\n\n### 第三轮版本记录\n\n| 版本 | 日期 | 变更 |\n|---|---|---|\n| {new_version} | 2026-10-08 | {note}；原型规则，未宣称实机或真人通过 |\n'
    p.write_text(s, encoding='utf-8', newline='\n')
    changed.append(str(p.relative_to(DOC)))

def replace(s, a, b):
    assert a in s, a[:90]
    return s.replace(a, b, 1)

